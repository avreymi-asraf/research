"""Minimal context-distillation experiment on a small LM (CPU-friendly).
Teacher = model + long rule prompt. Student = same model + LoRA, trained on (raw input -> teacher label),
WITHOUT the rule prompt. Evaluated against synthetic ground truth.
Usage: python ctx_distill.py MODEL_ID OUT_JSON N_TRAIN [EPOCHS]
"""
import sys, json, random, time, torch
from transformers import AutoTokenizer, AutoModelForCausalLM
from peft import LoraConfig, get_peft_model

MODEL, OUT, NTRAIN = sys.argv[1], sys.argv[2], int(sys.argv[3])
EPOCHS = int(sys.argv[4]) if len(sys.argv) > 4 else 3
REPLAY = int(sys.argv[5]) if len(sys.argv) > 5 else 0   # number of general-purpose replay prompts (self-generated by the unprompted base model)
torch.manual_seed(0); random.seed(0); torch.set_num_threads(4)

# ---------- synthetic task with exact ground truth ----------
RULES_PROMPT = """You triage customer messages. Reply with exactly one label and nothing else.
Rules, applied in this priority order (first match wins):
1. If the message mentions an error, crash, bug, or something not working -> BUG
2. Else if it mentions money, price, refund, invoice, or a charge -> BILLING
3. Else if it mentions a day of the week, a date, or a meeting time -> SCHEDULE
4. Otherwise -> OTHER
Labels: BUG, BILLING, SCHEDULE, OTHER."""
LABELS = ["BUG", "BILLING", "SCHEDULE", "OTHER"]
TRAIN_VOC = dict(
    bug=["error", "crash", "bug", "not working"],
    bill=["refund", "invoice", "price", "charge"],
    sched=["Monday", "Friday", "tomorrow at 3pm", "March 4th"],
)
# held-out surface forms (tests whether the RULE was learned rather than keywords memorised)
TEST_VOC = dict(
    bug=["exception", "froze", "glitch", "broken"],
    bill=["payment", "overcharged", "receipt", "fee"],
    sched=["Wednesday", "Sunday", "next week at noon", "June 12"],
)
FILL = ["I wanted to say that the {t} thing is on my mind.", "Quick note about the {t}.", "Hello team, regarding {t}.",
        "Just checking in, {t} again.", "Not sure who to ask, but {t}."]
NEUTRAL = ["the new logo looks great", "do you have a dark theme", "thanks for the quick help", "where is your office",
           "I love the product", "can you share the roadmap", "the onboarding video was helpful", "who is my account manager"]
def gen(voc, n, seed):
    r = random.Random(seed); out = []
    for _ in range(n):
        kinds = [k for k in ("bug", "bill", "sched") if r.random() < 0.35]
        parts = [r.choice(NEUTRAL)] if (not kinds or r.random() < 0.5) else []
        for k in kinds: parts.append(f"{r.choice(['about the','there is a','mentioning','re:'])} {r.choice(voc[k])}")
        r.shuffle(parts)
        text = r.choice(FILL).format(t=" and ".join(parts) if parts else r.choice(NEUTRAL))
        label = "BUG" if "bug" in kinds else "BILLING" if "bill" in kinds else "SCHEDULE" if "sched" in kinds else "OTHER"
        out.append((text, label))
    return out
train_x = [t for t, _ in gen(TRAIN_VOC, NTRAIN, 1)]            # labels deliberately NOT used for training
test_id = gen(TRAIN_VOC, 120, 2); test_ood = gen(TEST_VOC, 120, 3)
GENERAL_Q = ["What is the capital of France?", "Write a haiku about rain.", "What is 17 + 25?", "Give me one tip for sleeping better.",
             "Translate 'good morning' to Spanish.", "Name a primary color.", "Who wrote Hamlet?", "What does CPU stand for?",
             "Suggest a name for a cat.", "Explain gravity in one sentence."]

tok = AutoTokenizer.from_pretrained(MODEL); tok.padding_side = "left"
model = AutoModelForCausalLM.from_pretrained(MODEL, torch_dtype=torch.float32); model.eval()

def prompt(text, with_rules):
    msgs = ([{"role": "system", "content": RULES_PROMPT}] if with_rules else []) + [{"role": "user", "content": text}]
    return tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)

@torch.no_grad()
def generate(m, texts, with_rules, bs=8, max_new=6):
    outs = []
    for i in range(0, len(texts), bs):
        enc = tok([prompt(t, with_rules) for t in texts[i:i+bs]], return_tensors="pt", padding=True)
        g = m.generate(**enc, max_new_tokens=max_new, do_sample=False, pad_token_id=tok.pad_token_id)
        outs += [tok.decode(x[enc.input_ids.shape[1]:], skip_special_tokens=True).strip() for x in g]
    return outs
def norm(s):
    s = s.strip().upper().rstrip(".")
    return s if s in LABELS else "INVALID"
def acc(preds, gold): return sum(norm(p) == g for p, g in zip(preds, gold)) / len(gold)
def invalid(preds): return sum(norm(p) == "INVALID" for p in preds) / len(preds)

R = {"model": MODEL, "n_train": NTRAIN, "epochs": EPOCHS, "replay": REPLAY}
t0 = time.time()
# 1. Teacher labels the unlabeled inputs (prompted)
teacher_lab = generate(model, train_x, True)
R["teacher_train_label_invalid_rate"] = invalid(teacher_lab)
gold_train = [l for _, l in gen(TRAIN_VOC, NTRAIN, 1)]
R["teacher_acc_on_train_inputs"] = acc(teacher_lab, gold_train)
# 2. Baselines on test sets
for name, data in (("id", test_id), ("ood", test_ood)):
    xs, ys = [t for t, _ in data], [l for _, l in data]
    R[f"teacher_prompted_{name}"] = acc(generate(model, xs, True), ys)
    p = generate(model, xs, False); R[f"base_noprompt_{name}"] = acc(p, ys); R[f"base_noprompt_invalid_{name}"] = invalid(p)
R["t_baselines_s"] = time.time() - t0
REPLAY_Q = ["Why is the sky blue?", "Give me a recipe idea for dinner.", "What is the largest planet?", "Write a two-line poem about the sea.",
 "How do I say thank you in German?", "What is 9 times 8?", "Name three fruits.", "Who painted the Mona Lisa?", "What is the boiling point of water in Celsius?",
 "Explain what a noun is.", "Suggest a hobby for the weekend.", "What does RAM stand for?", "What is the capital of Japan?", "Tell me a fun fact about owls.",
 "How many days are in a week?", "Give one tip for studying.", "What is photosynthesis?", "Name a famous scientist.", "What is 100 divided by 4?", "Write a short greeting."]
replay_pairs = []
if REPLAY:
    rq = (REPLAY_Q * (REPLAY // len(REPLAY_Q) + 1))[:REPLAY]
    rr = generate(model, rq, False, max_new=40)    # base model, no prompt: its own distribution (anchor against drift)
    replay_pairs = list(zip(rq, rr))
# 3. Train student (LoRA) on (raw input -> teacher label), no rules in the input
pairs = [(x, l) for x, l in zip(train_x, teacher_lab) if norm(l) != "INVALID"]
raw_label = set(p[0] for p in pairs)
pairs = pairs + replay_pairs
R["n_train_used"] = len(pairs)
cfg = LoraConfig(r=16, lora_alpha=32, lora_dropout=0.0, target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"], task_type="CAUSAL_LM")
sm = get_peft_model(model, cfg); sm.train()
opt = torch.optim.AdamW([p for p in sm.parameters() if p.requires_grad], lr=2e-4)
tok.padding_side = "right"
losses = []
for ep in range(EPOCHS):
    random.shuffle(pairs)
    for i in range(0, len(pairs), 8):
        batch = pairs[i:i+8]
        full = [prompt(x, False) + (norm(l) if x in raw_label else l) + "<|im_end|>" for x, l in batch]
        enc = tok(full, return_tensors="pt", padding=True)
        labels = enc.input_ids.clone(); labels[enc.attention_mask == 0] = -100
        for j, (x, l) in enumerate(batch):   # mask the prompt tokens: loss only on the answer
            plen = len(tok(prompt(x, False)).input_ids); labels[j, :plen] = -100
        loss = sm(**enc, labels=labels).loss; loss.backward(); opt.step(); opt.zero_grad(); losses.append(loss.item())
sm.eval(); tok.padding_side = "left"
R["final_loss"] = sum(losses[-5:]) / 5; R["t_train_s"] = time.time() - t0
# 4. Evaluate the student WITHOUT rules; also with rules re-introduced; also unrelated-prompt leakage
for name, data in (("id", test_id), ("ood", test_ood)):
    xs, ys = [t for t, _ in data], [l for _, l in data]
    p = generate(sm, xs, False); R[f"student_noprompt_{name}"] = acc(p, ys); R[f"student_noprompt_invalid_{name}"] = invalid(p)
    R[f"student_with_rules_reintroduced_{name}"] = acc(generate(sm, xs, True), ys)
gq = generate(sm, GENERAL_Q, False, max_new=12)
R["general_q_answered_with_label"] = sum(norm(g.split()[0] if g.split() else "") != "INVALID" for g in gq) / len(gq)
R["general_q_samples"] = gq[:5]
with sm.disable_adapter():
    gb = generate(sm, GENERAL_Q, False, max_new=12)
R["general_q_base_samples"] = gb[:5]
R["t_total_s"] = time.time() - t0
json.dump(R, open(OUT, "w"), indent=1); print(json.dumps(R, indent=1))
